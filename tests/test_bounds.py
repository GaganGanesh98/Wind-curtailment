"""P3 -- the identified-set machinery (src/identification/).

The tests that matter here are behavioural, not arithmetic: that an exactly collinear
pair of cohorts leaves its SPLIT unidentified while its SUM stays pinned, and that the
truth lies inside the interval whenever the data were generated by a response the grid
can represent. A bounds routine that failed either of those would still pass a suite of
shape assertions.
"""

from __future__ import annotations

import numpy as np
import pytest

from src.method.bounds import (
    _bin_of, build_design, epsilon_from_bootstrap, identified_set,
    in_row_space, point_fit, pooled_fit,
)
from src.method import functionals as fx


def _arm(collinear: bool, seed: int = 0, T: int = 600):
    """Three cohorts; with `collinear=True` cohorts 1 and 2 share exposure and depth."""
    rng = np.random.default_rng(seed)
    price = -rng.random(T) * 80.0
    theta = np.array([-20.0, 0.0, 0.0]) if collinear else np.array([-20.0, 0.0, -5.0])
    s = (price[None, :] < theta[:, None]).astype(float)
    depth = np.maximum(0.0, theta[:, None] - price[None, :]) * s
    runlen = np.tile(rng.integers(1, 9, T).astype(float), (3, 1))
    w = np.array([0.5, 0.3, 0.2])
    days = np.array([f"2026-04-{1 + i // 24:02d}" for i in range(T)])
    return s, depth, runlen, w, price, days


def _design(collinear=True, **kw):
    s, depth, runlen, w, price, days = _arm(collinear, **kw)
    d = build_design(s, depth, w, runlen, cohort_ids=("a", "b", "c"))
    return d, s, depth, runlen, w, price, days


# ------------------------------------------------------------------- the design


def test_depth_bins_are_left_open_right_closed_and_zero_is_unbinned():
    edges = np.array([0.0, 2.0, 5.0, np.inf])
    np.testing.assert_array_equal(
        _bin_of(np.array([0.0, 0.1, 2.0, 2.1, 5.0, 5.1, 1e6]), edges),
        np.array([-1, 0, 0, 1, 1, 2, 2]),
    )


def test_design_reproduces_c_exactly_for_a_known_response():
    """X r IS the observation model: sum_k w_k s_kt r_k(z, L). Not approximately."""
    d, s, depth, runlen, w, _, _ = _design()
    lev = fx.run_levels(d, runlen, s)
    r = np.linspace(0.05, 0.95, d.n_cols)
    c_direct = np.zeros(d.rows.size)
    for k in range(s.shape[0]):
        on = s[k, d.rows] > 0
        jb = _bin_of(depth[k, d.rows], d.depth_edges)
        cols = np.array([d.col_of[(k, int(j), int(m))]
                         for j, m in zip(jb[on], lev[k, d.rows][on])])
        c_direct[np.flatnonzero(on)] += w[k] * r[cols]
    np.testing.assert_allclose(d.X @ r, c_direct, rtol=0, atol=1e-12)


def test_only_occupied_cells_get_a_column():
    d, *_ = _design()
    assert d.n_cols == len({k for k in d.col_of})
    assert (np.abs(d.X).sum(axis=0) > 0).all(), "an all-zero column is unconstrained"


def test_monotone_operators_encode_non_decreasing_in_depth_and_run():
    d, *_ = _design()
    rising = np.zeros(d.n_cols)
    for (k, j, m), i in d.col_of.items():
        rising[i] = 0.01 * j + 0.001 * m
    assert (d.A_depth @ rising >= -1e-12).all()
    if d.A_run.shape[0]:
        assert (d.A_run @ rising >= -1e-12).all()
    falling = -rising
    assert (d.A_depth @ falling <= 1e-12).all()


def test_no_exposure_raises_rather_than_returning_an_empty_design():
    with pytest.raises(ValueError, match="nothing to identify"):
        build_design(np.zeros((2, 10)), np.zeros((2, 10)), np.array([0.5, 0.5]))


# ------------------------------------------------------------------ epsilon


def test_epsilon_is_deterministic_and_sits_above_the_point_residual():
    d, s, depth, runlen, w, price, days = _design()
    r_true = np.clip(0.3 + 0.01 * d.col_depth_bin, 0, 1)
    c = d.X @ r_true + 0.01 * np.random.default_rng(1).standard_normal(d.n_rows)
    pf = point_fit(d, c)
    e1 = epsilon_from_bootstrap(d, c, days[d.rows], pf["r"])
    e2 = epsilon_from_bootstrap(d, c, days[d.rows], pf["r"])
    assert e1["eps"] == e2["eps"]
    assert e1["eps"] >= e1["rms_boot_median"] > 0


# ------------------------------------------- what is identified and what is not


def test_an_average_of_c_is_pinned_while_any_cohort_level_claim_is_not():
    """The P3 result in one assertion, and it is not the one I expected.

    `X r = c` pins every linear function OF c -- the fleet response in a price band is
    one, because it is the mean of c over those rows. It pins nothing that singles out
    a cohort, or even a GROUP of cohorts, because the split of a row's total between
    the cohorts exposed in it is exactly what the aggregate does not record. The first
    version of this test asserted that the collinear pair's capacity-weighted SUM
    would be pinned; it is not, and the reason is worth keeping: the pair's response
    can still be traded against the OTHER cohort exposed in the same quarter-hour.
    Only functionals of c survive that trade.
    """
    d, s, depth, runlen, w, price, days = _design(collinear=True)
    lev = fx.run_levels(d, runlen, s)
    r_true = np.clip(0.3 + 0.01 * d.col_depth_bin, 0, 1)
    c = d.X @ r_true
    pf = point_fit(d, c)
    eps = max(epsilon_from_bootstrap(d, c, days[d.rows], pf["r"])["eps"], 1e-6)

    fleet = fx.band_mean(d, price, -80.0, -5.0)
    grp = fx.group_mean(d, s, depth, lev, w, ("b", "c"))
    one = fx.cohort_mean(d, s, depth, lev, "b")
    assert fleet["defined"] and grp["defined"] and one["defined"]

    w_fleet = identified_set(d, c, fleet["lam"], eps)["width"]
    w_grp = identified_set(d, c, grp["lam"], eps)["width"]
    w_one = identified_set(d, c, one["lam"], eps)["width"]
    assert w_fleet < 1e-3, f"an average of c must be pinned, got {w_fleet}"
    assert w_grp > 100 * w_fleet, f"a group claim is not an average of c: {w_grp}"
    assert w_one > w_grp, f"one member must be at least as free as its group: {w_one}"


def test_a_separating_functional_is_outside_the_row_space_when_cohorts_are_collinear():
    d, s, depth, runlen, w, _, _ = _design(collinear=True)
    lev = fx.run_levels(d, runlen, s)
    sep = fx.difference(fx.cohort_mean(d, s, depth, lev, "b"),
                        fx.cohort_mean(d, s, depth, lev, "c"))
    assert not in_row_space(d.X, sep["lam"])["in_row_space"]
    agg = fx.band_mean(d, np.full(s.shape[1], -30.0), -50.0, -5.0)
    assert in_row_space(d.X, agg["lam"])["in_row_space"]


def test_exact_collinearity_strictly_widens_every_cohort_level_interval():
    """Collinearity is not the only thing that limits identification, but it bites.

    The same three functionals on the same generator, with cohorts b and c given
    identical exposure and depth in one arm and separated thresholds in the other.
    Every cohort-level interval must be strictly wider in the collinear arm; the
    fleet band mean must not care, because it is an average of c either way.
    """
    out = {}
    for collinear in (True, False):
        d, s, depth, runlen, w, price, days = _design(collinear=collinear)
        lev = fx.run_levels(d, runlen, s)
        r_true = np.clip(0.3 + 0.01 * d.col_depth_bin, 0, 1)
        c = d.X @ r_true
        pf = point_fit(d, c)
        eps = max(epsilon_from_bootstrap(d, c, days[d.rows], pf["r"])["eps"], 1e-6)
        specs = {
            "fleet": fx.band_mean(d, price, -80.0, -5.0),
            "one": fx.cohort_mean(d, s, depth, lev, "b"),
            "sep": fx.difference(fx.cohort_mean(d, s, depth, lev, "b"),
                                 fx.cohort_mean(d, s, depth, lev, "c")),
        }
        out[collinear] = {n: identified_set(d, c, sp["lam"], eps)["width"]
                          for n, sp in specs.items()}
    assert out[True]["one"] > out[False]["one"]
    assert out[True]["sep"] > out[False]["sep"]
    assert out[True]["fleet"] < 1e-3 and out[False]["fleet"] < 1e-3


def test_the_interval_contains_the_truth_when_the_grid_can_represent_it():
    d, s, depth, runlen, w, price, days = _design(collinear=True)
    lev = fx.run_levels(d, runlen, s)
    r_true = np.clip(0.2 + 0.015 * d.col_depth_bin, 0, 1)
    c = d.X @ r_true
    pf = point_fit(d, c)
    eps = max(epsilon_from_bootstrap(d, c, days[d.rows], pf["r"])["eps"], 1e-9)
    for spec in (fx.cohort_mean(d, s, depth, lev, "b"),
                 fx.group_mean(d, s, depth, lev, w, ("b", "c")),
                 fx.band_mean(d, price, -80.0, -5.0)):
        iv = identified_set(d, c, spec["lam"], eps)
        truth = fx.truth_value("", spec["lam"], r_true)
        assert iv["lo"] - 1e-6 <= truth <= iv["hi"] + 1e-6, (iv, truth)


def test_an_impossible_epsilon_is_reported_infeasible_not_silently_widened():
    d, s, depth, runlen, w, price, days = _design()
    c = np.full(d.n_rows, 5.0)            # unreachable: X r <= 1 by construction
    iv = identified_set(d, c, d.X.mean(axis=0), 1e-9)
    assert not iv["feasible"]
    assert "optimal" not in iv["status_lo"]


