def test_pooled_fit_gives_every_cohort_the_same_response_at_the_same_cell():
    d, s, depth, runlen, w, _, _ = _design()
    c = d.X @ np.clip(0.3 + 0.01 * d.col_depth_bin, 0, 1)
    out = pooled_fit(d, c)
    r = out["r_expanded"]
    assert r is not None and r.size == d.n_cols
    by_cell: dict[tuple[int, int], set[float]] = {}
    for (k, j, m), i in d.col_of.items():
        by_cell.setdefault((j, m), set()).add(round(float(r[i]), 9))
    assert all(len(v) == 1 for v in by_cell.values())


