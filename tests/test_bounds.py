def test_an_undefined_functional_says_so_rather_than_returning_zeros_silently():
    d, s, depth, runlen, w, _, _ = _design()
    lev = fx.run_levels(d, runlen, s)
    out = fx.cohort_mean(d, s, depth, lev, "nonexistent")
    assert not out["defined"] and "not in this design" in out["note"]
    empty = fx.band_mean(d, np.full(s.shape[1], -1.0), -100.0, -90.0)
    assert not empty["defined"] and empty["n_qh"] == 0


def test_counterfactual_energy_flags_clamped_extrapolation_as_a_lower_bound():
    d, s, depth, runlen, w, price, _ = _design()
    lev = fx.run_levels(d, runlen, s)
    pot = np.full(price.size, 20_000.0)
    out = fx.threshold_to_zero_energy(d, s, depth, lev, w, price, pot, "a")
    assert out["defined"]
    assert 0.0 <= out["coverage"] <= 1.0
    if out["coverage"] < 1.0:
        assert "LOWER BOUND" in out["note"]


def test_band_mean_is_the_mean_of_c_over_the_band():
    d, s, depth, runlen, w, price, _ = _design()
    r = np.linspace(0.1, 0.9, d.n_cols)
    spec = fx.band_mean(d, price, -50.0, -20.0)
    p = price[d.rows]
    m = (p > -50.0) & (p <= -20.0)
    np.testing.assert_allclose(spec["lam"] @ r, (d.X @ r)[m].mean(), rtol=1e-12)


